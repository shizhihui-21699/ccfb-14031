#!/usr/bin/env python3
"""
gen_constants.py — emits gen_constants.h with the numeric magic values that the
check() functions validate against. The correct serials live only in this
generator, never in the compiled binaries, mirroring a real release build.
"""
import os

MASK = 0xFFFFFFFF

def fnv1a32(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & MASK
    return h

# A 256-entry permutation table (Rijndael S-box) for table-lookup levels.
def sbox():
    p = [1] * 256
    for i in range(1, 256):
        p[i] = (p[i - 1] ^ ((p[i - 1] << 7) & 0xFF) ^ 0x1D) & 0xFF
    s = [0] * 256
    for i in range(256):
        s[p[i]] = i
    return s

SBOX = sbox()

# ---- the "secret" serials (only this file knows them) ----
SECRET_L1 = b"PLAN-42"
SECRET_L3 = b"ACME-2026"
SECRET_L4 = b"TBL-9Z4Q"
SECRET_L5 = b"SN-7F2A-X9"
SECRET_L6 = b"ULT-8K2M-51"

def c_array(name, vals, per=16):
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(vals), per):
        chunk = ", ".join(f"0x{v:02X}" for v in vals[i:i + per])
        lines.append("    " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)

out = []
out.append("/* AUTO-GENERATED by gen_constants.py — do not edit. */")
out.append("#ifndef GEN_CONSTANTS_H")
out.append("#define GEN_CONSTANTS_H")
out.append("")

# L1
out.append(f"#define L1_LEN {len(SECRET_L1)}")
out.append(c_array("L1_EXPECTED", list(SECRET_L1)))
out.append("")

# L3
l3_sum = sum(SECRET_L3) & 0xFFFFFFFF
out.append(f"#define L3_LEN {len(SECRET_L3)}")
out.append(f"#define L3_SUM 0x{l3_sum:08X}u")
out.append(f"#define L3_FIRST {SECRET_L3[0]}")
out.append(f"#define L3_LAST  {SECRET_L3[-1]}")
out.append("")

# L4
l4_len = len(SECRET_L4)
l4_targets = [SBOX[b] for b in SECRET_L4]
out.append(f"#define L4_LEN {l4_len}")
out.append(c_array("L4_SBOX", SBOX))
out.append(c_array("L4_TARGET", l4_targets, per=8))
out.append("")

# L5
l5_hash = fnv1a32(SECRET_L5)
out.append(f"#define L5_LEN {len(SECRET_L5)}")
out.append(f"#define L5_HASH 0x{l5_hash:08X}u")
out.append("")

# L6 — layered: length gate, prefix check, hash of tail, table on middle
l6_len = len(SECRET_L6)
prefix = SECRET_L6[:4]                 # "ULT-"
middle = SECRET_L6[4:8]                # "8K2M"
tail = SECRET_L6[8:]                   # "51"
l6_sum = sum(SECRET_L6) & 0xFFFFFFFF
l6_hash = fnv1a32(tail)
l6_targets = [SBOX[b] for b in middle]
out.append(f"#define L6_LEN {l6_len}")
out.append(f"#define L6_SUM 0x{l6_sum:08X}u")
out.append(c_array("L6_PREFIX", list(prefix), per=8))
out.append(f"#define L6_MID_OFF 4")
out.append(f"#define L6_TAIL_OFF 8")
out.append(f"#define L6_HASH 0x{l6_hash:08X}u")
out.append(c_array("L6_TARGET", l6_targets, per=8))
out.append("")

out.append("#endif")

dst = os.path.join(os.path.dirname(__file__), "gen_constants.h")
with open(dst, "w") as f:
    f.write("\n".join(out) + "\n")

# Also print the secrets so we can cross-check the analyzer's output.
for name, val in [("L1", SECRET_L1), ("L3", SECRET_L3), ("L4", SECRET_L4),
                  ("L5", SECRET_L5), ("L6", SECRET_L6)]:
    print(f"{name} ground-truth serial: {val.decode()}")
print("wrote", dst)
